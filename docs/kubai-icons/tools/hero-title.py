#!/usr/bin/env python3
"""Draws the Chinese home headline as SVG outlines, into site/src/components/hero-title-zh.ts.

The headline uses the rounded cut of Alimama FangYuanTi. Outlines show it to every visitor
without shipping the font file. Rerun this after changing the phrases below.

Needs fonttools and the font installed (FONT overrides its path).
"""
import json
import os
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

PHRASES = ["让图标", "动起来"]
WEIGHT = 600
ROUND = 100
# The em box of a CJK font runs from 880 above the baseline to 120 below it.
ASCENT = 880

source = os.environ.get("FONT", os.path.expanduser("~/Library/Fonts/AlimamaFangYuanTiVF-Thin-2.ttf"))
font = instancer.instantiateVariableFont(TTFont(source), {"wght": WEIGHT, "BEVL": ROUND})
glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
scale = 1000 / font["head"].unitsPerEm


def draw(phrase):
    pen = SVGPathPen(glyphs, ntos=lambda n: str(round(n)))
    x = 0
    for char in phrase:
        glyph = glyphs[cmap[ord(char)]]
        glyph.draw(TransformPen(pen, (scale, 0, 0, -scale, x, ASCENT)))
        x += glyph.width * scale
    return {"width": round(x), "d": pen.getCommands()}


outlines = {phrase: draw(phrase) for phrase in PHRASES}
out = Path(__file__).resolve().parent.parent / "site/src/components/hero-title-zh.ts"
out.write_text(
    "// Generated by tools/hero-title.py. Outlines of the Chinese home headline.\n"
    f"export const HERO_TITLE_ZH: Record<string, {{ width: number; d: string }}> = {json.dumps(outlines, ensure_ascii=False)};\n",
    encoding="utf-8",
)
print(f"{out.name}: {out.stat().st_size} bytes")
